# Generates src/smb/symbols.js from the assembled SMB disassembly symbol tables.
import json, re, sys
ref=sys.argv[1]
labels=json.load(open('labels.json')); syms=json.load(open('labels_sym.json'))
def names(path):
    out=[]
    for l in open(path):
        m=re.match(r'^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=',l)
        if m: out.append(m.group(1))
    return out
ram=names(ref+'/src/ram.asm'); defs=names(ref+'/src/defs.asm')
def fmt(d):
    return '{\n'+''.join(f'  {k}: 0x{v:04x},\n' for k,v in d.items())+'}'
code={k:v for k,v in sorted(labels.items()) if v>=0x8000}
R={k:syms[k] for k in ram if k in syms}
C={k:syms[k] for k in defs if k in syms}
with open(sys.argv[2],'w') as f:
    f.write('// Generated by tools/gen_symbols.py from the SMB disassembly (doppelganger/Xkeeper0).\n')
    f.write('// Addresses only: routine/table locations in the PRG ROM, RAM variable addresses and\n// named constants. No ROM data lives here; the game reads everything from the user\'s ROM.\n\n')
    f.write('export const L = '+fmt(code)+';\n\n')
    f.write('export const R = '+fmt(R)+';\n\n')
    f.write('export const C = '+fmt(C)+';\n')
print(len(code),len(R),len(C))
